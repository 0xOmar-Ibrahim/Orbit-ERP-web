# contract_number is generated by the server (CTR-YYYY-NNNN) and can't be set or edited
CONTRACT_FIELDS = [
    "employee_id",
    "contract_type",
    "start_date",
    "end_date",
    "position_id",
    "schedule_id",
    "wage",
    "currency",
    "status",
]


def validate_contract_values(start_date, end_date, wage):
    errors = {}

    # Mirrors the chk_contract_date_order DB constraint
    if start_date and end_date and end_date <= start_date:
        errors["end_date"] = "End date must be later than start date."

    if wage is not None and wage < 0:
        errors["wage"] = "Wage cannot be negative."

    if errors:
        raise serializers.ValidationError(errors)


class AddEmploymentContractSerializer(serializers.ModelSerializer):
    employee_id = serializers.PrimaryKeyRelatedField(
        source="employee",
        queryset=Employee.objects.all()
    )
    position_id = serializers.PrimaryKeyRelatedField(
        source="position",
        queryset=JobPosition.objects.all(),
        required=False,
        allow_null=True
    )
    schedule_id = serializers.PrimaryKeyRelatedField(
        source="schedule",
        queryset=WorkSchedule.objects.all(),
        required=False,
        allow_null=True
    )

    class Meta:
        model = EmploymentContract
        fields = CONTRACT_FIELDS

    def validate(self, attrs):
        validate_contract_values(
            attrs.get("start_date"),
            attrs.get("end_date"),
            attrs.get("wage"),
        )
        return attrs

    def create(self, validated_data):
        contract_number = generate_unique_code(
            EmploymentContract, "contract_number", account_type=3
        )
        return EmploymentContract.objects.create(
            **validated_data,
            contract_number=contract_number,
        )


